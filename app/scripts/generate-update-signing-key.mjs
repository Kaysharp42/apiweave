#!/usr/bin/env node
// Generates the Ed25519 key pair that signs APIWeave's update manifests.
//
//   node scripts/generate-update-signing-key.mjs | gh secret set UPDATE_SIGNING_PRIVATE_KEY
//
// The public key is written into electron/update_signing_key.ts, which is
// compiled into the app and committed. The private key goes to stdout only —
// pipe it straight into the GitHub secret, keep an offline backup, and never
// commit it. It never touches the disk here.
//
// Refuses to replace a real key without --force: installs only accept updates
// signed by the key they were built with, so a new key strands every install
// in the field (see "Rotating the key" in docs/reference/release-and-updates.md).
import { generateKeyPairSync } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const KEY_FILE = fileURLToPath(new URL("../electron/update_signing_key.ts", import.meta.url))

if (!readFileSync(KEY_FILE, "utf8").includes('= "PLACEHOLDER"') && !process.argv.includes("--force")) {
  console.error(
    "electron/update_signing_key.ts already holds a real key. Replacing it means installs built " +
      "with the old key refuse every update signed with the new one. Re-run with --force if that is intended.",
  )
  process.exit(1)
}

const { publicKey, privateKey } = generateKeyPairSync("ed25519")
const publicDer = publicKey.export({ format: "der", type: "spki" }).toString("base64")

writeFileSync(
  KEY_FILE,
  `// The public half of the Ed25519 key that signs APIWeave's update manifests.
// The release workflow signs with the private half (the
// UPDATE_SIGNING_PRIVATE_KEY secret), and the updater refuses to install any
// update this key does not verify. See docs/reference/release-and-updates.md.
//
// Generated by scripts/generate-update-signing-key.mjs on ${new Date().toISOString().slice(0, 10)}.
export const UPDATE_SIGNING_PUBLIC_KEY: string = "${publicDer}"
`,
)

process.stdout.write(privateKey.export({ format: "pem", type: "pkcs8" }))
console.error(`
Wrote the public key to ${KEY_FILE} — commit that file.
The private key was printed to stdout. If you did not pipe it into
\`gh secret set UPDATE_SIGNING_PRIVATE_KEY\`, add it now as a repository secret
named UPDATE_SIGNING_PRIVATE_KEY (Settings → Secrets and variables → Actions),
store a backup offline, and clear it from your terminal scrollback.`)
